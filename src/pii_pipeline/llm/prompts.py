#: 단일 이미지(타일 1개) user 메시지.
#:
#: 타일 번호나 페이지 내 위치를 **적지 않는다.** 모델은 자기가 받은 이미지에
#: 대해서만 답하고, 페이지 좌표로의 환산은 ``detect.py`` 가 한다. 이러면
#: user 메시지도 고정되어 prefix caching 이 이미지 앞까지 걸린다.
USER_VLM = (
    "이 문서 이미지에서 개인정보를 모두 찾아 그대로 옮겨 적어라. "
    "표가 있으면 모든 행을 빠뜨리지 말고 확인하라."
)


def build_user(hint: str = "") -> str:
    """user 메시지를 만든다.

    Args:
        hint: 문서 종류를 아는 경우의 추가 지시 (예: "가족관계증명서다").
            **비워 두는 것이 기본이다** — 채우면 prefix caching 이 깨지고,
            문서 종류를 잘못 알려주면 모델이 없는 칸을 찾는다.
            공백만 있는 값은 비운 것으로 본다 (YAML 에서 ``hint: " "`` 로
            들어와도 캐싱이 깨지지 않아야 한다).

    Returns:
        user 메시지 문자열.
    """
    trimmed = hint.strip()
    if not trimmed:
        return USER_VLM
    return f"{USER_VLM}\n{trimmed}"
